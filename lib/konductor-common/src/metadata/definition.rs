use serde::{Deserialize, Serialize};

use crate::error::{ControlPlaneError, ValidationExceptionField, ValidationExceptionReason};

/// Reserved built-in metadata field names owned by the platform. Configuration
/// can neither define nor shadow them; they are stamped on every event.
pub const RESERVED_ROOT_FIELDS: [&str; 4] = [
    "schemaVersion",
    "idempotencyKey",
    "publishedAt",
    "metadataRevision",
];

/// Keys that JavaScript object consumers treat unsafely. Rejected at every
/// object level, not only at the metadata root.
const UNSAFE_KEYS: [&str; 3] = ["__proto__", "prototype", "constructor"];

/// Maximum number of extension nodes (fields plus nested objects) a definition
/// may contain. Built-ins are implicit and do not count.
pub const MAX_EXTENSION_NODES: usize = 64;

/// Maximum number of nested object levels below the metadata root.
pub const MAX_OBJECT_LEVELS: usize = 4;

/// Maximum serialized size of the canonical definition document.
pub const MAX_DEFINITION_BYTES: usize = 16 * 1024;

/// The bounded catalogue of platform generators. Every extension field is
/// generated by the platform from trusted context; producers never supply
/// values. The variant set is the single source of truth for supported
/// generators on both the API and the editor UI.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum Generator {
    UuidV4,
    UtcTimestamp,
    UtcDate,
    AwsRegion,
    Organisation,
    Environment,
}

impl Generator {
    pub const ALL: [Generator; 6] = [
        Generator::UuidV4,
        Generator::UtcTimestamp,
        Generator::UtcDate,
        Generator::AwsRegion,
        Generator::Organisation,
        Generator::Environment,
    ];

    pub const fn as_str(self) -> &'static str {
        match self {
            Generator::UuidV4 => "uuid-v4",
            Generator::UtcTimestamp => "utc-timestamp",
            Generator::UtcDate => "utc-date",
            Generator::AwsRegion => "aws-region",
            Generator::Organisation => "organisation",
            Generator::Environment => "environment",
        }
    }

    /// Parses the wire identifier. Unknown generators are rejected by serde
    /// during deserialization; this serves non-serde call sites.
    pub fn parse(value: &str) -> Option<Self> {
        Self::ALL.iter().copied().find(|g| g.as_str() == value)
    }

    /// The generated value's type and primitive validation constraint,
    /// derived from the generator rather than authored by administrators.
    pub const fn generated_type(self) -> GeneratedType {
        match self {
            Generator::UuidV4 => GeneratedType::UuidV4,
            Generator::UtcTimestamp => GeneratedType::UtcTimestamp,
            Generator::UtcDate => GeneratedType::UtcDate,
            Generator::AwsRegion | Generator::Organisation | Generator::Environment => {
                GeneratedType::NonEmptyString
            }
        }
    }

    /// Human-readable description of the trusted source the platform reads.
    pub const fn source_description(self) -> &'static str {
        match self {
            Generator::UuidV4 => "platform RNG, generated once per admitted event",
            Generator::UtcTimestamp => "one captured admission instant",
            Generator::UtcDate => "the same captured admission instant",
            Generator::AwsRegion => "trusted processing region",
            Generator::Organisation => "resolved platform organisation",
            Generator::Environment => "authorized publish API stage",
        }
    }
}

/// The value shape a generator produces. Types are inferred, never authored.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GeneratedType {
    UuidV4,
    UtcTimestamp,
    UtcDate,
    NonEmptyString,
}

impl GeneratedType {
    /// Validation semantics of generated values, shown read-only in the editor.
    pub const fn constraint_description(self) -> &'static str {
        match self {
            GeneratedType::UuidV4 => "string in UUID v4 format",
            GeneratedType::UtcTimestamp => "UTC RFC 3339 timestamp with millisecond precision",
            GeneratedType::UtcDate => "UTC calendar date (YYYY-MM-DD)",
            GeneratedType::NonEmptyString => "non-empty string",
        }
    }
}

/// An extension node: a generated leaf field or a nested object.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "kebab-case")]
pub enum MetadataNode {
    Field {
        name: String,
        generator: Generator,
    },
    Object {
        name: String,
        #[serde(default)]
        children: Vec<MetadataNode>,
    },
}

impl MetadataNode {
    pub fn name(&self) -> &str {
        match self {
            MetadataNode::Field { name, .. } | MetadataNode::Object { name, .. } => name,
        }
    }
}

/// A metadata definition: extension fields and objects only. The built-ins
/// (`schemaVersion`, `idempotencyKey`, `publishedAt`, `metadataRevision`) are
/// implicit in every revision and cannot be configured.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct MetadataDefinition {
    #[serde(default)]
    pub children: Vec<MetadataNode>,
}

/// One generated extension field with its generator identity, for read-only
/// display in composed contracts and the admin UI.
#[derive(Debug, Clone, PartialEq)]
pub struct GeneratedField {
    /// The field's location in the metadata tree: dotted paths below the
    /// root for fields inside nested objects.
    pub path: String,
    pub generator: Generator,
}

fn collect_generated_fields(
    children: &[MetadataNode],
    prefix: &str,
    fields: &mut Vec<GeneratedField>,
) {
    for node in children {
        let path = if prefix.is_empty() {
            node.name().to_string()
        } else {
            format!("{prefix}.{}", node.name())
        };
        match node {
            MetadataNode::Field { generator, .. } => fields.push(GeneratedField {
                path,
                generator: *generator,
            }),
            MetadataNode::Object { children, .. } => {
                collect_generated_fields(children, &path, fields)
            }
        }
    }
}

/// A definition that passed every structural check. Constructing this type is
/// the only way to reach generation, compilation, and additive comparison, so
/// downstream code never handles an unvalidated tree.
#[derive(Debug, Clone, PartialEq)]
pub struct ValidatedMetadataDefinition(MetadataDefinition);

impl ValidatedMetadataDefinition {
    /// Validates structure, names, bounds, and serialized size, collecting
    /// every violation so callers can display complete field-level errors.
    pub fn validate(definition: MetadataDefinition) -> Result<Self, ControlPlaneError> {
        let mut violations = Vec::new();
        let mut node_count = 0usize;
        validate_children(&definition.children, 0, &mut violations, &mut node_count);
        let validated = Self(definition);
        match validated.canonical_bytes() {
            Ok(bytes) if bytes.len() > MAX_DEFINITION_BYTES => {
                violations.push(ValidationExceptionField {
                    name: "definition".to_string(),
                    message: format!(
                        "definition is {} bytes; the maximum is {MAX_DEFINITION_BYTES}",
                        bytes.len()
                    ),
                })
            }
            Ok(_) => {}
            Err(message) => violations.push(ValidationExceptionField {
                name: "definition".to_string(),
                message,
            }),
        }
        if violations.is_empty() {
            Ok(validated)
        } else {
            Err(definition_error(violations))
        }
    }

    pub fn definition(&self) -> &MetadataDefinition {
        &self.0
    }

    pub fn children(&self) -> &[MetadataNode] {
        &self.0.children
    }

    /// Every generated leaf field in definition order, with dotted paths for
    /// fields nested inside objects — the read-only generator catalogue for
    /// composed contracts and the admin UI.
    pub fn generated_fields(&self) -> Vec<GeneratedField> {
        let mut fields = Vec::new();
        collect_generated_fields(&self.0.children, "", &mut fields);
        fields
    }

    /// Count of extension nodes (fields plus nested objects).
    pub fn extension_node_count(&self) -> usize {
        count_nodes(&self.0.children)
    }

    /// The canonical serialized form stored with each immutable revision and
    /// used for definition digests.
    pub fn canonical_bytes(&self) -> Result<Vec<u8>, String> {
        serde_json::to_vec(&self.0).map_err(|e| format!("definition is not serializable: {e}"))
    }

    /// The sha-256 digest of the canonical definition, hex-encoded: the
    /// stable identity stored with each revision and environment pointer.
    pub fn definition_digest(&self) -> Result<String, String> {
        use sha2::{Digest, Sha256};
        let bytes = self.canonical_bytes()?;
        Ok(Sha256::digest(&bytes)
            .iter()
            .map(|b| format!("{b:02x}"))
            .collect())
    }
}

fn validate_children(
    children: &[MetadataNode],
    ancestor_objects: usize,
    violations: &mut Vec<ValidationExceptionField>,
    node_count: &mut usize,
) {
    let mut seen: Vec<&str> = Vec::with_capacity(children.len());
    for node in children {
        let path = node.name().to_string();
        if seen.contains(&node.name()) {
            violations.push(ValidationExceptionField {
                name: path.clone(),
                message: "duplicate field name in the same object".to_string(),
            });
        } else {
            seen.push(node.name());
        }
        validate_name(&path, ancestor_objects == 0, violations);
        *node_count += 1;
        if *node_count == MAX_EXTENSION_NODES + 1 {
            violations.push(ValidationExceptionField {
                name: "definition".to_string(),
                message: format!(
                    "definition exceeds the maximum of {MAX_EXTENSION_NODES} extension nodes"
                ),
            });
        }
        if let MetadataNode::Object { children, .. } = node {
            let object_level = ancestor_objects + 1;
            if object_level > MAX_OBJECT_LEVELS {
                violations.push(ValidationExceptionField {
                    name: path.clone(),
                    message: format!(
                        "object nesting exceeds the maximum of {MAX_OBJECT_LEVELS} object levels"
                    ),
                });
            }
            validate_children(children, object_level, violations, node_count);
        }
    }
}

fn validate_name(name: &str, at_root: bool, violations: &mut Vec<ValidationExceptionField>) {
    if UNSAFE_KEYS.contains(&name) {
        violations.push(ValidationExceptionField {
            name: name.to_string(),
            message: "unsafe object key is not allowed at any level".to_string(),
        });
        return;
    }
    if at_root && RESERVED_ROOT_FIELDS.contains(&name) {
        violations.push(ValidationExceptionField {
            name: name.to_string(),
            message: "reserved built-in metadata field cannot be redefined".to_string(),
        });
        return;
    }
    if !valid_name_segment(name) {
        violations.push(ValidationExceptionField {
            name: name.to_string(),
            message:
                "field name must match [A-Za-z][A-Za-z0-9_]{0,63} (1-64 characters, starting with a letter)"
                    .to_string(),
        });
    }
}

fn valid_name_segment(name: &str) -> bool {
    let bytes = name.as_bytes();
    match bytes {
        [] => false,
        [first, rest @ ..] => {
            if !first.is_ascii_alphabetic() || bytes.len() > 64 {
                return false;
            }
            rest.iter().all(|b| b.is_ascii_alphanumeric() || *b == b'_')
        }
    }
}

fn count_nodes(children: &[MetadataNode]) -> usize {
    children
        .iter()
        .map(|node| match node {
            MetadataNode::Field { .. } => 1,
            MetadataNode::Object { children, .. } => 1 + count_nodes(children),
        })
        .sum()
}

fn definition_error(violations: Vec<ValidationExceptionField>) -> ControlPlaneError {
    let summary = violations
        .iter()
        .map(|v| v.message.clone())
        .collect::<Vec<_>>()
        .join("; ");
    ControlPlaneError::ValidationException {
        message: format!("invalid metadata definition: {summary}"),
        reason: ValidationExceptionReason::FieldValidationFailed,
        field_list: Some(violations),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn field(name: &str, generator: Generator) -> MetadataNode {
        MetadataNode::Field {
            name: name.to_string(),
            generator,
        }
    }

    fn object(name: &str, children: Vec<MetadataNode>) -> MetadataNode {
        MetadataNode::Object {
            name: name.to_string(),
            children,
        }
    }

    fn field_list_of(err: ControlPlaneError) -> Vec<ValidationExceptionField> {
        match err {
            ControlPlaneError::ValidationException { field_list, .. } => {
                field_list.unwrap_or_default()
            }
            other => panic!("expected ValidationException, got {other}"),
        }
    }

    #[test]
    fn empty_definition_is_the_builtin_baseline() {
        let validated = ValidatedMetadataDefinition::validate(MetadataDefinition::default());
        assert!(validated.is_ok());
    }

    #[test]
    fn reserved_builtin_names_are_rejected_at_root() {
        for reserved in RESERVED_ROOT_FIELDS {
            let definition = MetadataDefinition {
                children: vec![field(reserved, Generator::UuidV4)],
            };
            let err = ValidatedMetadataDefinition::validate(definition).unwrap_err();
            let violations = field_list_of(err);
            assert_eq!(violations.len(), 1, "{reserved}: {violations:?}");
            assert!(violations[0].message.contains("reserved"));
        }
    }

    #[test]
    fn unsafe_keys_are_rejected_at_every_level() {
        for key in UNSAFE_KEYS {
            let nested = MetadataDefinition {
                children: vec![object("wrapper", vec![field(key, Generator::AwsRegion)])],
            };
            let err = ValidatedMetadataDefinition::validate(nested).unwrap_err();
            assert!(
                field_list_of(err)
                    .iter()
                    .any(|v| v.message.contains("unsafe")),
                "{key} must be rejected when nested"
            );
        }
    }

    #[test]
    fn unsafe_keys_matching_the_name_pattern_are_still_rejected() {
        // `prototype` and `constructor` match [A-Za-z][A-Za-z0-9_]{0,63}; the
        // explicit unsafe-key check must catch them before the pattern does.
        let definition = MetadataDefinition {
            children: vec![field("prototype", Generator::Environment)],
        };
        let err = ValidatedMetadataDefinition::validate(definition).unwrap_err();
        assert!(field_list_of(err)[0].message.contains("unsafe"));
    }

    #[test]
    fn name_pattern_is_enforced() {
        for bad in [
            "",
            "9starts-with-digit",
            "has-dash",
            "has space",
            "has.dot",
            "__leading",
        ] {
            let definition = MetadataDefinition {
                children: vec![field(bad, Generator::AwsRegion)],
            };
            let err = ValidatedMetadataDefinition::validate(definition).unwrap_err();
            assert!(
                field_list_of(err)
                    .iter()
                    .any(|v| v.message.contains("field name must match")),
                "{bad:?} must be rejected"
            );
        }
    }

    #[test]
    fn name_length_bound_is_enforced() {
        let sixty_four = "a".repeat(64);
        let sixty_five = "a".repeat(65);
        assert!(ValidatedMetadataDefinition::validate(MetadataDefinition {
            children: vec![field(&sixty_four, Generator::AwsRegion)]
        })
        .is_ok());
        assert!(ValidatedMetadataDefinition::validate(MetadataDefinition {
            children: vec![field(&sixty_five, Generator::AwsRegion)]
        })
        .is_err());
    }

    #[test]
    fn duplicate_names_in_one_object_are_rejected() {
        let definition = MetadataDefinition {
            children: vec![
                field("eventId", Generator::UuidV4),
                field("eventId", Generator::UtcDate),
            ],
        };
        let err = ValidatedMetadataDefinition::validate(definition).unwrap_err();
        assert!(field_list_of(err)[0].message.contains("duplicate"));
    }

    #[test]
    fn four_object_levels_are_allowed_and_five_are_rejected() {
        let chain_of = |levels: usize| {
            let mut children = vec![field("leaf", Generator::AwsRegion)];
            for level in 0..levels {
                children = vec![object(&format!("obj{level}"), children)];
            }
            MetadataDefinition { children }
        };
        assert!(ValidatedMetadataDefinition::validate(chain_of(4)).is_ok());
        let err = ValidatedMetadataDefinition::validate(chain_of(5)).unwrap_err();
        assert!(
            field_list_of(err)
                .iter()
                .any(|v| v.message.contains("object nesting")),
            "five object levels must be rejected"
        );
    }

    #[test]
    fn extension_node_bound_is_enforced() {
        let at_limit = MetadataDefinition {
            children: (0..MAX_EXTENSION_NODES)
                .map(|i| field(&format!("f{i}"), Generator::AwsRegion))
                .collect(),
        };
        assert!(ValidatedMetadataDefinition::validate(at_limit).is_ok());

        let over_limit = MetadataDefinition {
            children: (0..=MAX_EXTENSION_NODES)
                .map(|i| field(&format!("f{i}"), Generator::AwsRegion))
                .collect(),
        };
        let err = ValidatedMetadataDefinition::validate(over_limit).unwrap_err();
        assert!(field_list_of(err)[0].message.contains("extension nodes"));
    }

    #[test]
    fn nested_objects_count_toward_the_node_bound() {
        let children = (0..MAX_EXTENSION_NODES)
            .map(|i| field(&format!("f{i}"), Generator::AwsRegion))
            .collect();
        let definition = MetadataDefinition {
            children: vec![object("wrapper", children)],
        };
        let err = ValidatedMetadataDefinition::validate(definition).unwrap_err();
        assert!(field_list_of(err)[0].message.contains("extension nodes"));
    }

    #[test]
    fn definition_size_bound_is_enforced() {
        // Structural limits (64-char names, 64 nodes) keep valid definitions
        // around 8 KiB, so the 16 KiB canonical-size check is a backstop for
        // future format evolution. It runs alongside name checks, so an
        // oversized document trips it even when names are also invalid.
        let oversized = MetadataDefinition {
            children: vec![field(&"a".repeat(20_000), Generator::AwsRegion)],
        };
        let err = ValidatedMetadataDefinition::validate(oversized).unwrap_err();
        assert!(
            field_list_of(err)
                .iter()
                .any(|v| v.name == "definition" && v.message.contains("bytes")),
            "oversized definition must be rejected"
        );
    }

    #[test]
    fn maximally_sized_valid_definition_stays_under_the_size_backstop() {
        let deep = (0..4).fold(
            vec![MetadataNode::Field {
                name: "x".repeat(64),
                generator: Generator::UtcTimestamp,
            }],
            |children, level| vec![object(&format!("o{level}"), children)],
        );
        let mut children: Vec<MetadataNode> = (0..MAX_EXTENSION_NODES - 5)
            .map(|i| field(&format!("f{i}"), Generator::AwsRegion))
            .collect();
        children.extend(deep);
        let validated =
            ValidatedMetadataDefinition::validate(MetadataDefinition { children }).unwrap();
        let bytes = validated.canonical_bytes().unwrap();
        assert!(
            bytes.len() < MAX_DEFINITION_BYTES,
            "structural limits must keep definitions under the size backstop, got {}",
            bytes.len()
        );
    }

    #[test]
    fn all_violations_are_reported_together() {
        let definition = MetadataDefinition {
            children: vec![
                field("schemaVersion", Generator::UuidV4),
                field("9bad", Generator::AwsRegion),
            ],
        };
        let err = ValidatedMetadataDefinition::validate(definition).unwrap_err();
        assert_eq!(field_list_of(err).len(), 2);
    }

    #[test]
    fn generator_type_inference_matches_the_catalogue() {
        assert_eq!(Generator::UuidV4.generated_type(), GeneratedType::UuidV4);
        assert_eq!(
            Generator::UtcTimestamp.generated_type(),
            GeneratedType::UtcTimestamp
        );
        assert_eq!(Generator::UtcDate.generated_type(), GeneratedType::UtcDate);
        for generator in [
            Generator::AwsRegion,
            Generator::Organisation,
            Generator::Environment,
        ] {
            assert_eq!(
                generator.generated_type(),
                GeneratedType::NonEmptyString,
                "{}",
                generator.as_str()
            );
        }
        for generator in Generator::ALL {
            assert!(!generator
                .generated_type()
                .constraint_description()
                .is_empty());
            assert!(!generator.source_description().is_empty());
        }
    }

    #[test]
    fn generator_wire_names_round_trip() {
        for generator in Generator::ALL {
            assert_eq!(Generator::parse(generator.as_str()), Some(generator));
            let value = serde_json::to_value(generator).unwrap();
            assert_eq!(value, serde_json::json!(generator.as_str()));
            let parsed: Generator = serde_json::from_value(value).unwrap();
            assert_eq!(parsed, generator);
        }
        assert_eq!(Generator::parse("not-a-generator"), None);
    }

    #[test]
    fn unknown_generator_is_rejected_by_deserialization() {
        let raw = serde_json::json!({
            "children": [{"kind": "field", "name": "eventId", "generator": "eval-script"}]
        });
        let result: Result<MetadataDefinition, _> = serde_json::from_value(raw);
        assert!(result.is_err());
    }

    #[test]
    fn definition_round_trips_through_serialization() {
        let definition = MetadataDefinition {
            children: vec![
                field("eventId", Generator::UuidV4),
                object("correlation", vec![field("traceDate", Generator::UtcDate)]),
            ],
        };
        let json = serde_json::to_value(&definition).unwrap();
        let parsed: MetadataDefinition = serde_json::from_value(json).unwrap();
        assert_eq!(parsed, definition);
        let validated = ValidatedMetadataDefinition::validate(definition).unwrap();
        assert_eq!(validated.extension_node_count(), 3);
        assert_eq!(validated.children().len(), 2);
        let bytes = validated.canonical_bytes().unwrap();
        let reparsed: MetadataDefinition =
            serde_json::from_slice(&bytes).expect("canonical bytes are valid JSON");
        assert!(ValidatedMetadataDefinition::validate(reparsed).is_ok());
    }

    #[test]
    fn canonical_bytes_are_stable_for_a_given_definition() {
        let definition = MetadataDefinition {
            children: vec![
                field("eventId", Generator::UuidV4),
                field("region", Generator::AwsRegion),
            ],
        };
        let first = ValidatedMetadataDefinition::validate(definition.clone())
            .unwrap()
            .canonical_bytes()
            .unwrap();
        let second = ValidatedMetadataDefinition::validate(definition)
            .unwrap()
            .canonical_bytes()
            .unwrap();
        assert_eq!(first, second);
    }
}
