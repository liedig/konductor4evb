<script setup lang="ts">
import type { DraftMutations } from '~/utils/metadataModel'
import type { MetadataGenerator, MetadataNode, MetadataRevision } from '~/types/api'

/**
 * Additive definition editor over the shared controls. The draft starts as a
 * clone of the latest saved revision; inherited nodes render locked and can
 * neither be edited nor removed. Local edits are kept in component state and
 * survive validation errors — nothing is persisted until 6.3's save flow.
 */
const props = withDefaults(defineProps<{
  predecessor?: MetadataRevision | null
  busy?: boolean
}>(), {
  predecessor: null,
  busy: false,
})

const draft = ref<MetadataNode[]>(draftFromSaved(props.predecessor?.definition?.children))

watch(() => props.predecessor?.revision, () => {
  draft.value = draftFromSaved(props.predecessor?.definition?.children)
})

/** Paths of nodes inherited from the saved predecessor; locked nodes cannot be renamed, so paths are stable. */
const savedPaths = computed(() => {
  const paths = new Set<string>()
  function walk(nodes: MetadataNode[], parent: string) {
    for (const node of nodes) {
      const path = parent ? `${parent}.${node.name}` : node.name
      paths.add(path)
      if (node.kind === 'object') walk(node.children ?? [], path)
    }
  }
  walk(props.predecessor?.definition?.children ?? [], '')
  return paths
})

const violations = computed(() => validateDraft(draft.value))
const nodeCount = computed(() => countNodes(draft.value))
const levels = computed(() => objectLevels(draft.value))
const bytes = computed(() => definitionBytes({ children: draft.value }))
const valid = computed(() => violations.value.length === 0)

const mutator: DraftMutations = {
  rename(node, value) {
    node.name = value
  },
  setGenerator(node, value) {
    if (node.kind === 'field') node.generator = value as MetadataGenerator
  },
  addField(parent) {
    childrenOf(parent).push({ kind: 'field', name: '', generator: 'uuid-v4' })
  },
  addObject(parent) {
    childrenOf(parent).push({ kind: 'object', name: '', children: [] })
  },
  remove(node) {
    detach(draft.value, null, node)
  },
  violation(path) {
    const exact = violations.value.find(v => v.name === path)
    if (exact) return exact.message
    return violations.value
      .filter(v => v.name.startsWith(`${path}.`))
      .map(v => `${v.name}: ${v.message}`)
      .join('; ') || undefined
  },
  isLocked(path) {
    return savedPaths.value.has(path)
  },
  busy() {
    return props.busy
  },
}

provide('metadataDraftMutations', mutator)

function childrenOf(parent: MetadataNode | null): MetadataNode[] {
  if (parent === null) return draft.value
  if (parent.kind !== 'object') return draft.value
  parent.children ??= []
  return parent.children
}

function detach(nodes: MetadataNode[], parent: MetadataNode | null, target: MetadataNode): void {
  const index = nodes.indexOf(target)
  if (index !== -1) {
    if (mutator.isLocked(pathOf(target))) return
    nodes.splice(index, 1)
    return
  }
  for (const node of nodes) {
    if (node.kind === 'object') detach(node.children ?? [], node, target)
  }
}

function pathOf(target: MetadataNode): string {
  function walk(nodes: MetadataNode[], parent: string): string | undefined {
    for (const node of nodes) {
      const path = parent ? `${parent}.${node.name}` : node.name
      if (node === target) return path
      if (node.kind === 'object') {
        const found = walk(node.children ?? [], path)
        if (found) return found
      }
    }
    return undefined
  }
  return walk(draft.value, '') ?? ''
}

const definitionViolations = computed(() =>
  violations.value.filter(v => v.name === 'definition'),
)

defineExpose({
  draft,
  violations,
  valid,
})
</script>

<template>
  <NxCard title="Definition editor">
    <p class="mb-4 text-sm text-muted">
      Additive extension fields, generated by the platform. Saved fields are
      immutable; a revision save creates the next immutable revision and never activates it.
    </p>

    <div class="mb-4 flex flex-wrap gap-4 text-xs text-faint" role="status">
      <span :class="{ 'text-danger': nodeCount > METADATA_LIMITS.extensionNodesMax }">
        Extension nodes: {{ nodeCount }} / {{ METADATA_LIMITS.extensionNodesMax }}
      </span>
      <span :class="{ 'text-danger': levels > METADATA_LIMITS.objectLevelsMax }">
        Object levels: {{ levels }} / {{ METADATA_LIMITS.objectLevelsMax }}
      </span>
      <span :class="{ 'text-danger': bytes > METADATA_LIMITS.definitionBytesMax }">
        Definition: {{ bytes }} / {{ METADATA_LIMITS.definitionBytesMax }} bytes
      </span>
    </div>

    <MetadataNodeEditor :nodes="draft" />

    <div v-if="!draft.length" class="mt-2">
      <NxEmptyState
        title="No extension fields yet"
        body="Add generated fields to extend every event's metadata. Existing events keep their exact recorded revision."
      />
    </div>

    <div class="mt-4 flex gap-2">
      <NxButton variant="secondary" size="sm" :disabled="busy" @click="mutator.addField(null)">
        Add field
      </NxButton>
      <NxButton variant="secondary" size="sm" :disabled="busy" @click="mutator.addObject(null)">
        Add object
      </NxButton>
    </div>

    <ul v-if="definitionViolations.length" class="mt-4 flex flex-col gap-1" role="alert">
      <li v-for="violation in definitionViolations" :key="violation.message" class="text-sm text-danger">
        {{ violation.message }}
      </li>
    </ul>
  </NxCard>
</template>
